// Generates src/data/teams.json and src/data/players.json from ESPN.
// ESPN doesn't allow browser requests (no CORS), so this runs at dev time.
// Usage: node scripts/fetch-nba-data.mjs
import { writeFile, mkdir } from 'node:fs/promises';

const BASE = 'https://site.api.espn.com/apis';

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

const standings = await get(`${BASE}/v2/sports/basketball/nba/standings`);
const teams = [];
for (const conf of standings.children) {
  const conference = conf.name.startsWith('East') ? 'East' : 'West';
  for (const entry of conf.standings.entries) {
    const t = entry.team;
    teams.push({
      id: t.abbreviation,
      espnId: t.id,
      name: t.displayName,
      shortName: t.shortDisplayName,
      conference,
      logo: t.logos?.[0]?.href ?? null,
    });
  }
}
teams.sort((a, b) => a.name.localeCompare(b.name));
if (teams.length !== 30) throw new Error(`expected 30 teams, got ${teams.length}`);

const players = [];
const coaches = [];
for (const team of teams) {
  const roster = await get(`${BASE}/site/v2/sports/basketball/nba/teams/${team.espnId}/roster`);
  for (const a of roster.athletes ?? []) {
    players.push({
      name: a.displayName,
      team: team.id,
      rookie: (a.experience?.years ?? 1) === 0,
    });
  }
  for (const c of roster.coach ?? []) {
    coaches.push({ name: `${c.firstName} ${c.lastName}`, team: team.id });
  }
}
players.sort((a, b) => a.name.localeCompare(b.name));

await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/data/teams.json', import.meta.url), JSON.stringify(teams, null, 2) + '\n');
await writeFile(
  new URL('../src/data/players.json', import.meta.url),
  JSON.stringify({ players, coaches }, null, 2) + '\n',
);
// Award pick whitelist for the database. Re-run this SQL in Supabase after refreshing.
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const options = new Set([
  ...players.map((p) => `('player', ${q(p.name)})`),
  ...players.filter((p) => p.rookie).map((p) => `('rookie', ${q(p.name)})`),
  ...coaches.map((c) => `('coach', ${q(c.name)})`),
]);
await writeFile(
  new URL('../supabase/award_options.sql', import.meta.url),
  `-- Generated by scripts/fetch-nba-data.mjs on ${new Date().toISOString().slice(0, 10)}. Safe to re-run.\n` +
    `-- Existing picks are kept even if a name drops off the list.\n` +
    `delete from public.award_options;\n` +
    `insert into public.award_options (kind, name) values\n  ${[...options].join(',\n  ')};\n`,
);

console.log(`${teams.length} teams, ${players.length} players (${players.filter((p) => p.rookie).length} rookies), ${coaches.length} coaches`);
